import { DeviceProject } from '../types/hardware';

export type FirmwareTarget = 'arduino' | 'esp-idf' | 'platformio' | 'micropython';

export function generateFirmware(project: DeviceProject, target: FirmwareTarget): string {
  switch (target) {
    case 'arduino':
      return generateArduinoCode(project);
    case 'esp-idf':
      return generateEspIdfCode(project);
    case 'platformio':
      return generatePlatformIoConfig(project);
    case 'micropython':
      return generateMicroPythonCode(project);
  }
}

function generateArduinoCode(project: DeviceProject): string {
  // Extract connected I2C, SPI, UART and GPIO pins from wires
  const pinDefinitions: string[] = [];
  let hasI2C = false;
  let hasSPI = false;
  let hasUART = false;

  for (const wire of project.wires) {
    const netName = wire.netName || `WIRE_${wire.id.toUpperCase()}`;
    // find mcu pin if from or to is mcu
    let mcuPin = '';
    if (wire.fromComponentId === 'mcu') {
      const p = project.mcu.pins.find(pin => pin.id === wire.fromPinId);
      if (p && p.gpioNumber !== undefined) mcuPin = `${p.gpioNumber}`;
    } else if (wire.toComponentId === 'mcu') {
      const p = project.mcu.pins.find(pin => pin.id === wire.toPinId);
      if (p && p.gpioNumber !== undefined) mcuPin = `${p.gpioNumber}`;
    }

    if (mcuPin) {
      pinDefinitions.push(`#define PIN_${netName.replace(/[^A-Za-z0-9_]/g, '_').toUpperCase()} ${mcuPin}`);
    }

    if (wire.wireType === 'i2c') hasI2C = true;
    if (wire.wireType === 'spi') hasSPI = true;
    if (wire.wireType === 'uart') hasUART = true;
  }

  const uniquePinDefs = Array.from(new Set(pinDefinitions)).join('\n');

  return `// ==============================================================
// Auto-generated Arduino C++ Sketch for: ${project.name}
// Target MCU: ${project.mcu.name} (${project.mcu.family})
// Generated by ESP-Forge Studio
// ==============================================================

#include <Arduino.h>
${hasI2C ? '#include <Wire.h>\n' : ''}${hasSPI ? '#include <SPI.h>\n' : ''}
// --- Pin Assignments ---
${uniquePinDefs || '// No direct digital GPIO mapping needed'}

// --- Connected Modules ---
${project.components.map(c => `// - ${c.name} (${c.category.toUpperCase()}, ${c.protocol})`).join('\n')}

void setup() {
  Serial.begin(115200);
  delay(1000);
  Serial.println(F("========================================"));
  Serial.println(F("Booting ${project.name}..."));
  Serial.println(F("MCU Architecture: ${project.mcu.cpuArchitecture}"));
  Serial.println(F("Clock Speed: ${project.mcu.clockSpeedMhz} MHz"));
  Serial.println(F("========================================"));

${hasI2C ? `  // Initialize I2C Bus\n  #if defined(PIN_I2C_SDA) && defined(PIN_I2C_SCL)\n  Wire.begin(PIN_I2C_SDA, PIN_I2C_SCL);\n  Serial.println(F("[OK] Hardware I2C initialized"));\n  #else\n  Wire.begin();\n  #endif\n` : ''}
${hasSPI ? `  // Initialize High-Speed SPI Bus\n  #if defined(PIN_SPI_SCK) && defined(PIN_SPI_MOSI) && defined(PIN_SPI_MISO)\n  SPI.begin(PIN_SPI_SCK, PIN_SPI_MISO, PIN_SPI_MOSI);\n  Serial.println(F("[OK] Hardware SPI initialized"));\n  #else\n  SPI.begin();\n  #endif\n` : ''}
  Serial.println(F("Hardware self-test completed. Entering main task loop."));
}

void loop() {
  // Telemetry heartbeat
  static unsigned long lastTick = 0;
  if (millis() - lastTick > 2000) {
    lastTick = millis();
    Serial.print(F("[HEARTBEAT] Free Heap: "));
    Serial.print(ESP.getFreeHeap());
    Serial.println(F(" bytes"));
  }

  delay(10);
}
`;
}

function generateEspIdfCode(project: DeviceProject): string {
  return `/*
 * ESP-IDF C Project: ${project.name}
 * Target SoC: ${project.mcu.family}
 * Architecture: ${project.mcu.cpuArchitecture}
 * Generated by ESP-Forge Studio
 */

#include <stdio.h>
#include <string.h>
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "esp_system.h"
#include "esp_log.h"
#include "driver/gpio.h"
#include "driver/i2c.h"
#include "driver/spi_master.h"

static const char *TAG = "${project.name.replace(/[^A-Za-z0-9]/g, '_').substring(0, 16)}";

void app_main(void)
{
    ESP_LOGI(TAG, "Initializing hardware subsystems for ${project.name}...");
    ESP_LOGI(TAG, "SoC Family: ${project.mcu.family} | Cores: ${project.mcu.cores}");
    ESP_LOGI(TAG, "Active components configured: ${project.components.length}");

    // Flash & PSRAM verification
    ESP_LOGI(TAG, "Total Free Heap: %lu bytes", (unsigned long)esp_get_free_heap_size());

    while (1) {
        vTaskDelay(pdMS_TO_TICKS(1000));
        ESP_LOGI(TAG, "System running nominally. Duty cycle: ${project.activeDutyCyclePercent}%%");
    }
}
`;
}

function generatePlatformIoConfig(project: DeviceProject): string {
  let platform = 'espressif32';
  let boardId = 'esp32-s3-devkitc-1';

  if (project.mcu.family === 'ESP32-P4') boardId = 'esp32-p4-preview';
  else if (project.mcu.family === 'ESP32-C6') boardId = 'esp32-c6-devkitm-1';
  else if (project.mcu.family === 'Arduino-Uno-R4') {
    platform = 'renesas-ra';
    boardId = 'uno_r4_wifi';
  } else if (project.mcu.family === 'Arduino-Giga-R1') {
    platform = 'ststm32';
    boardId = 'giga_r1_m7';
  } else if (project.mcu.family === 'Raspberry-Pi-Pico-2') {
    platform = 'raspberrypi';
    boardId = 'rp2350';
  } else if (project.mcu.family.startsWith('Radxa')) {
    platform = 'linux_arm64';
    boardId = project.mcu.family === 'Radxa-Rock-5B' ? 'radxa_rock5b' : 'radxa_zero3w';
  }

  return `; PlatformIO Project Configuration File
; Project: ${project.name}
; Generated by ESP-Forge Studio

[platformio]
default_envs = ${project.mcu.family.toLowerCase().replace(/[^a-z0-9]/g, '_')}

[env:${project.mcu.family.toLowerCase().replace(/[^a-z0-9]/g, '_')}]
platform = ${platform}
board = ${boardId}
framework = ${platform === 'linux_arm64' ? 'custom' : 'arduino'}
monitor_speed = 115200
upload_speed = 921600

build_flags =
    -D CORE_DEBUG_LEVEL=3
    -D BOARD_HAS_PSRAM
    -D FLASH_SIZE_MB=${project.mcu.flashSizeMb}
    -D PSRAM_SIZE_MB=${project.mcu.psramSizeMb}

lib_deps =
    adafruit/Adafruit GFX Library
    adafruit/Adafruit BusIO
    bblanchon/ArduinoJson @ ^7.0.0
`;
}

function generateMicroPythonCode(project: DeviceProject): string {
  return `# MicroPython Boot & Main Driver
# Device: ${project.name} (${project.mcu.family})
# Generated by ESP-Forge Studio

import machine
import time
import gc

print("Initializing ${project.name} on ${project.mcu.family}...")
print("CPU Frequency:", machine.freq() // 1000000, "MHz")
print("Allocated Modules: ${project.components.length}")

# Memory garbage collection
gc.collect()
print("Initial Free RAM:", gc.mem_free(), "bytes")

while True:
    print("Heartbeat tick | Free memory:", gc.mem_free())
    time.sleep(2)
`;
}
