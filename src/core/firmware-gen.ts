import { DeviceProject } from '../types/hardware';

export type FirmwareTarget = 'arduino' | 'espidf' | 'platformio' | 'micropython' | 'linux_python';

export function generateFirmware(project: DeviceProject, target: FirmwareTarget): string {
  switch (target) {
    case 'arduino':
      return generateArduinoCpp(project);
    case 'espidf':
      return generateEspIdfC(project);
    case 'platformio':
      return generatePlatformIoConfig(project);
    case 'micropython':
      return generateMicroPython(project);
    case 'linux_python':
      return generateLinuxPython(project);
  }
}

function generateArduinoCpp(project: DeviceProject): string {
  const isArduinoR4 = project.mcu.family === 'Arduino-Uno-R4';
  const hasDisplay = project.components.some((c) => c.category === 'display');
  const hasModem = project.components.some((c) => c.category === 'connectivity');
  const hasSensor = project.components.some((c) => c.category === 'sensor');
  const hasRelay = project.components.some((c) => c.category === 'actuator');

  return `/**
 * =========================================================================
 * Project: ${project.name} (v${project.version})
 * Target SoC: ${project.mcu.name} (${project.mcu.cpuArchitecture})
 * Generated by ESP-Forge Studio on ${new Date().toISOString().split('T')[0]}
 * =========================================================================
 */

#include <Arduino.h>
#include <Wire.h>
#include <SPI.h>
${isArduinoR4 ? '#include "Arduino_LED_Matrix.h"\nArduinoLEDMatrix matrix;\n' : ''}
${hasDisplay ? '// LovyanGFX / TFT_eSPI Display Driver\n#include <LovyanGFX.hpp>\n' : ''}
${hasSensor ? '#include <Adafruit_Sensor.h>\n#include <Adafruit_BME680.h>\nAdafruit_BME680 bme;\n' : ''}

// Pin Definitions Mapped from Schematic Netlist
${project.wires
  .filter((w) => w.fromComponentId === 'mcu')
  .map((w) => {
    const pin = project.mcu.pins.find((p) => p.id === w.fromPinId);
    return `#define PIN_${w.signalType.toUpperCase()} ${pin?.gpioNumber ?? pin?.label ?? 0}`;
  })
  .filter((v, i, a) => a.indexOf(v) === i)
  .join('\n')}

void setup() {
  Serial.begin(115200);
  delay(1000);
  Serial.println(F("========================================"));
  Serial.println(F("⚡ Booting: ${project.name}"));
  Serial.println(F("Target MCU: ${project.mcu.name}"));
  Serial.println(F("========================================"));

  // Initialize System Buses
  Wire.begin();
  SPI.begin();

  ${isArduinoR4 ? 'matrix.begin();\n  Serial.println(F("[INIT] 12x8 LED Matrix Display online"));\n' : ''}

  ${hasSensor ? `if (!bme.begin(0x77)) {
    Serial.println(F("[WARN] BME680 sensor not detected on I2C bus 0x77"));
  } else {
    Serial.println(F("[INIT] BME680 environmental sensor initialized"));
    bme.setTemperatureOversampling(BME680_OS_8X);
    bme.setHumidityOversampling(BME680_OS_2X);
  }` : ''}

  ${hasRelay ? `// Setup High-Voltage Relays
  pinMode(PIN_GPIO, OUTPUT);
  digitalWrite(PIN_GPIO, LOW);
  Serial.println(F("[INIT] Dual Relays armed in DE-ENERGIZED state"));` : ''}

  Serial.println(F("[SYS] Hardware initialization complete. Entering main task loop."));
}

void loop() {
  ${hasSensor ? `if (bme.performReading()) {
    Serial.print(F("🌡️ Temp: ")); Serial.print(bme.temperature); Serial.print(F("°C | "));
    Serial.print(F("Humidity: ")); Serial.print(bme.humidity); Serial.print(F("% | "));
    Serial.print(F("Pressure: ")); Serial.print(bme.pressure / 100.0); Serial.println(F(" hPa"));
  }` : `Serial.println(F("Heartbeat: ${project.name} running normally..."));`}

  delay(2000);
}
`;
}

function generateEspIdfC(project: DeviceProject): string {
  return `/**
 * ESP-IDF Production Firmware: ${project.name}
 * Target: ${project.mcu.name}
 */

#include <stdio.h>
#include "esp_log.h"
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "driver/gpio.h"
#include "driver/i2c.h"

static const char *TAG = "${project.id.toUpperCase()}";

void app_main(void) {
    ESP_LOGI(TAG, "Starting ${project.name} on ESP-IDF v5.2");
    ESP_LOGI(TAG, "CPU Clock: ${project.mcu.clockSpeedMhz} MHz, Architecture: ${project.mcu.cpuArchitecture}");

    // Configure I2C Master Bus
    i2c_config_t conf = {
        .mode = I2C_MODE_MASTER,
        .sda_io_num = GPIO_NUM_8,
        .scl_io_num = GPIO_NUM_9,
        .sda_pullup_en = GPIO_PULLUP_ENABLE,
        .scl_pullup_en = GPIO_PULLUP_ENABLE,
        .master.clk_speed = 400000
    };
    i2c_param_config(I2C_NUM_0, &conf);
    i2c_driver_install(I2C_NUM_0, conf.mode, 0, 0, 0);
    ESP_LOGI(TAG, "I2C driver initialized @ 400kHz");

    while (1) {
        ESP_LOGI(TAG, "Uptime tick: Free Heap = %u bytes", (unsigned int)esp_get_free_heap_size());
        vTaskDelay(pdMS_TO_TICKS(5000));
    }
}
`;
}

function generatePlatformIoConfig(project: DeviceProject): string {
  let platform = 'espressif32';
  let board = 'esp32-s3-devkitc-1';
  let framework = 'arduino';

  if (project.mcu.family === 'ESP32-P4') {
    platform = 'https://github.com/espressif/platform-espressif32.git';
    board = 'esp32-p4-ev-board';
    framework = 'espidf';
  } else if (project.mcu.family === 'Arduino-Uno-R4') {
    platform = 'renesas-ra';
    board = 'uno_r4_wifi';
    framework = 'arduino';
  } else if (project.mcu.family === 'Arduino-Giga-R1') {
    platform = 'ststm32';
    board = 'giga_r1_m7';
    framework = 'arduino';
  } else if (project.mcu.family === 'Radxa-Zero-3W' || project.mcu.family === 'Radxa-Rock-5B') {
    platform = 'linux_arm64';
    board = 'generic_linux';
    framework = 'custom';
  } else if (project.mcu.family === 'Raspberry-Pi-Pico-2') {
    platform = 'raspberrypi';
    board = 'pico2';
    framework = 'arduino';
  }

  return `[platformio]
default_envs = ${project.mcu.family.toLowerCase().replace(/[^a-z0-9]/g, '_')}

[env:${project.mcu.family.toLowerCase().replace(/[^a-z0-9]/g, '_')}]
platform = ${platform}
board = ${board}
framework = ${framework}
monitor_speed = 115200
upload_speed = 921600

build_flags =
    -D PROJECT_NAME=\\""${project.name}\\""
    -D CORE_DEBUG_LEVEL=3
    -D BOARD_HAS_PSRAM
    -mfix-esp32-psram-cache-issue

lib_deps =
    lovyan03/LovyanGFX @ ^1.1.16
    adafruit/Adafruit BME680 Library @ ^2.0.4
    bblanchon/ArduinoJson @ ^7.0.4
`;
}

function generateMicroPython(project: DeviceProject): string {
  return `# MicroPython Firmware Script
# Target: ${project.mcu.name}

from machine import Pin, I2C, SPI
import time

print("⚡ Starting ${project.name} MicroPython Runtime")
i2c = I2C(0, scl=Pin(9), sda=Pin(8), freq=400000)
print("I2C Devices scan:", [hex(x) for x in i2c.scan()])

while True:
    print("Heartbeat tick from ${project.mcu.name}")
    time.sleep(2)
`;
}

function generateLinuxPython(project: DeviceProject): string {
  return `#!/usr/bin/env python3
"""
Linux Hardware Daemon for ${project.mcu.name}
SoC: ${project.mcu.cpuArchitecture} (Linux 6.1 Kernel)
"""

import time
import os
import smbus2

print(f"⚡ Starting {project.name} Linux Hardware Daemon")
print(f"Running on {os.uname().sysname} {os.uname().release} ({os.uname().machine})")

try:
    bus = smbus2.SMBus(1)
    print("Mounted Linux /dev/i2c-1 hardware bus")
except Exception as e:
    print(f"Warning: /dev/i2c-1 fallback: {e}")

while True:
    print("Hardware daemon active. Polling sensors and telemetry...")
    time.sleep(3)
`;
}
